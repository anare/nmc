#!/usr/bin/env bash
set -euo pipefail

root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
cache=$(mktemp -d "${TMPDIR:-/tmp}/nmc-gates.XXXXXX")
status_file="$root/plan/STATUS.md"
temporary_status="$cache/STATUS.md"
trap 'rm -rf "$cache"' EXIT
export NMC_ROOT="$root"
export NMC_GATE_CACHE="$cache"

declare -a phases=()
if (($#)); then
	for argument in "$@"; do
		if [[ "$argument" =~ ^[0-9]+$ ]]; then
			phases+=("$(printf '%02d' "$argument")")
		elif [[ "$argument" =~ ^[0-9]+-[0-9]+$ ]]; then
			start=${argument%-*}
			end=${argument#*-}
			for ((phase=start; phase<=end; phase++)); do
				phases+=("$(printf '%02d' "$phase")")
			done
		else
			printf 'usage: %s [phase-number ... | start-end]\n' "$0" >&2
			exit 2
		fi
	done
else
	for phase_file in "$root"/plan/gates/phase-*.sh; do
		phases+=("${phase_file##*phase-}")
		phases[-1]=${phases[-1]%.sh}
	done
fi

declare -A seen=()
unique=()
for phase in "${phases[@]}"; do
	if [[ ! -f "$root/plan/gates/phase-$phase.sh" ]]; then
		printf 'unknown phase: %s\n' "$phase" >&2
		exit 2
	fi
	if [[ -z ${seen[$phase]+x} ]]; then
		seen[$phase]=1
		unique+=("$phase")
	fi
done

printf '# Rebuild phase status\n\n' >"$temporary_status"
printf 'Generated by `plan/run.sh` from the phase gates.\n\n| Phase | Result |\n| --- | --- |\n' >>"$temporary_status"
failed=0
for phase in "${unique[@]}"; do
	printf '== Phase %s ==\n' "$phase"
	if bash "$root/plan/gates/phase-$phase.sh"; then
		printf '| %s | PASS |\n' "$phase" >>"$temporary_status"
	else
		printf '| %s | FAIL |\n' "$phase" >>"$temporary_status"
		failed=1
	fi
done
printf '\n' >>"$temporary_status"
if ((failed)); then
	printf 'Result: one or more selected phases failed.\n' >>"$temporary_status"
else
	printf 'Result: all %d selected phase(s) passed.\n' "${#unique[@]}" >>"$temporary_status"
fi
mv "$temporary_status" "$status_file"
if ((failed)); then
	exit 1
fi
printf 'All %d selected phase(s) passed; status written to plan/STATUS.md\n' "${#unique[@]}"
